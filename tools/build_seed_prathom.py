#!/usr/bin/env python3
"""Build supabase/prathom/seed_prathom.sql — ประถม catalogue (ป.4, ป.5 coming soon; ป.6 external → live ป.6 app).
Curriculum outline only (subject / chapter / topic names from the public ป.6 page). No items, no people.
For REVIEW BY PETER (owner of kruom-examgym-p6). Not applied to kruom-examgym-ms. Local test stack only."""
import json, sys
C = json.load(open(sys.argv[1] if len(sys.argv) > 1 else '/tmp/p6cur.json'))
q = lambda s: 'null' if s is None else "'" + str(s).replace("'", "''") + "'"
SUBJ = [('MA','คณิตศาสตร์','🔢','#007AFF'),('SC','วิทยาศาสตร์','🔬','#34C759'),('EN','ภาษาอังกฤษ','🔤','#AF52DE'),
        ('TH','ภาษาไทย','📖','#FF9500'),('SO','สังคมศึกษา','🌏','#5AC8FA')]
P6_URL = 'https://kruom9.github.io/kruom-xexamgym-p6/'
out = ['-- GENERATED by tools/build_seed_prathom.py — ประถม catalogue (outline only; no items, no people).',
       '-- Idempotent. Run AFTER seed.sql. For review by the ประถม project owner before use anywhere but the local stack.',
       'begin;']
for i, (g, name, status, url) in enumerate([('P4','ป.4','coming_soon',None),('P5','ป.5','coming_soon',None),('P6','ป.6','external',P6_URL)]):
    out.append(f"insert into public.grades (code,name_th,app_name,sort,status,external_url,room_max) values ({q(g)},{q(name)},{q('Exam Gym ปิยมิตรประถม '+name)},{11+i},{q(status)},{q(url)},6) "
               "on conflict (code) do update set name_th=excluded.name_th, app_name=excluded.app_name, sort=excluded.sort, status=excluded.status, external_url=excluded.external_url, room_max=excluded.room_max;")
    for k, (sc, sn, ic, col) in enumerate(SUBJ, 1):
        st = 'needs_content' if g != 'P6' else 'imported'
        note = 'ยังไม่มีเนื้อหา — รอผู้อำนวยการกำหนดแหล่งเนื้อหา (Helix ไม่มีเอกสารประถม)' if g != 'P6' else 'โครงหัวข้อจากระบบ ป.6 ที่ใช้งานอยู่ (ข้อสอบยังอยู่ในระบบเดิม)'
        out.append(f"insert into public.subjects (id,grade_code,code,name_th,icon,color,course_codes,status,note,sort) values ({q(g+'-'+sc)},{q(g)},{q(sc)},{q(sn)},{q(ic)},{q(col)},'{{}}'::text[],{q(st)},{q(note)},{k}) "
                   "on conflict (id) do update set name_th=excluded.name_th, status=excluded.status, note=excluded.note, sort=excluded.sort;")
n = 0
for s in C['subjects']:
    for ch in s['chapters']:
        for t in ch['topics']:
            n += 1
            out.append("insert into public.strands (id,subject_id,grade_code,code,name_th,group_no,group_name,indicators,concepts,source,status,sort) values ("
                       f"{q('P6-'+t['id'])},{q('P6-'+s['id'])},'P6',{q(t['code'])},{q(t['name'])},{ch['no']},{q('บทที่ %d %s' % (ch['no'], ch['name']))},{q(t.get('basis'))},"
                       f"{q(json.dumps(t.get('concepts', []), ensure_ascii=False))}::jsonb,'live ป.6 CURRICULUM (kruom-xexamgym-p6)','live',{n}) "
                       "on conflict (id) do update set name_th=excluded.name_th, group_no=excluded.group_no, group_name=excluded.group_name, indicators=excluded.indicators, concepts=excluded.concepts;")
out.append('commit;')
open('supabase/prathom/seed_prathom.sql', 'w').write('\n'.join(out) + '\n')
print('strands', n)
